def _unique(values: list[str]) -> list[str]:
    seen: set[str] = set()
    output: list[str] = []
    for value in values:
        value = str(value or "").strip()
        if value and value not in seen:
            seen.add(value)
            output.append(value)
    return output


VIDEO_SOURCE_VALIDATED = "VALIDATED_BYTE_SOURCE"
VIDEO_SOURCE_DEFERRED = "SAFE_BROWSER_BYTE_SOURCE"
VIDEO_SOURCE_FORBIDDEN = "FORBIDDEN_DRIVE_UI"
VIDEO_SOURCE_UNVERIFIED = "UNVERIFIED_SOURCE"


def _classify_public_video_candidate(value: str, *, validated: bool = False) -> str:
    """Classify a public video URL without ever promoting Drive UI to playback.

    ``validated=True`` means the backend already proved that the URL returns video
    bytes anonymously. Without that proof only the deliberately narrow set of
    known Drive byte-delivery URLs and same-origin media assets can survive as a
    browser-deferred fallback. Viewer/navigation URLs are always forbidden.
    """
    raw = str(value or "").strip()
    if not raw:
        return VIDEO_SOURCE_UNVERIFIED
    lowered = raw.casefold()
    if lowered.startswith(("javascript:", "data:", "vbscript:")):
        return VIDEO_SOURCE_FORBIDDEN
    if "accounts.google.com" in lowered or "servicelogin" in lowered:
        return VIDEO_SOURCE_FORBIDDEN
    if "drive.google.com/open" in lowered:
        return VIDEO_SOURCE_FORBIDDEN
    if re.search(r"drive\.google\.com/file/d/[^/?#]+(?:/(?:preview|view))?(?:[/?#]|$)", lowered):
        return VIDEO_SOURCE_FORBIDDEN
    if "drive.google.com" in lowered and re.search(r"/(?:preview|view)(?:[/?#]|$)", lowered):
        return VIDEO_SOURCE_FORBIDDEN
    if validated:
        return VIDEO_SOURCE_VALIDATED

    # Same-origin derivatives generated by StudioFrame are always byte assets.
    if lowered.startswith(("/assets/", "assets/", "./assets/")):
        return VIDEO_SOURCE_DEFERRED

    try:
        parsed = urlsplit(raw)
    except ValueError:
        return VIDEO_SOURCE_UNVERIFIED
    if parsed.scheme.casefold() not in {"http", "https"}:
        return VIDEO_SOURCE_UNVERIFIED
    host = (parsed.hostname or "").casefold()
    path = (parsed.path or "").casefold()
    if host == "drive.google.com" and path.rstrip("/") == "/uc":
        return VIDEO_SOURCE_DEFERRED
    if host == "drive.usercontent.google.com" and path.startswith("/download"):
        return VIDEO_SOURCE_DEFERRED
    return VIDEO_SOURCE_UNVERIFIED


def _public_video_candidate_allowed(value: str) -> bool:
    """Return False only for explicitly forbidden public video/navigation URLs.

    This helper is used to assert an already-selected public manifest. Whether an
    unvalidated candidate may be *deferred* is intentionally decided by the
    narrower ``_public_video_deferred_candidate_allowed`` helper below.
    """
    return _classify_public_video_candidate(value, validated=True) == VIDEO_SOURCE_VALIDATED


def _public_video_deferred_candidate_allowed(value: str) -> bool:
    """Allow browser fallback only for known direct byte-delivery surfaces."""
    return _classify_public_video_candidate(value, validated=False) == VIDEO_SOURCE_DEFERRED




def _media_delivery_config(settings: dict[str, Any]) -> dict[str, Any]:
    """Return the active public-media delivery contract.

    V7.4 restores the original zero-cost product boundary: Google Drive owns the
    media, GitHub Pages owns only the static site, and the public StudioFrame
    player consumes anonymous *read-only byte* URLs from Drive. Historical
    Gateway fields remain readable for rollback/audit but can never become a
    publication prerequisite in drive_public_bytes mode.
    """
    builder = settings.get("site_builder") if isinstance(settings.get("site_builder"), dict) else {}
    cfg = builder.get("media_delivery") if isinstance(builder.get("media_delivery"), dict) else {}
    mode = str(cfg.get("mode") or "drive_public_bytes").strip().lower()
    if mode not in {"drive_public_bytes", "private_drive_gateway"}:
        mode = "drive_public_bytes"
    base = str(os.environ.get("STUDIOFRAME_MEDIA_GATEWAY_BASE_URL") or cfg.get("public_base_url") or "").strip().rstrip("/")
    raw_state = str(cfg.get("gateway_state") or "superseded").strip().lower()
    gateway_state = raw_state if raw_state in {"provisioning", "active", "error", "superseded"} else "superseded"
    return {
        "mode": mode,
        "public_base_url": base,
        "gateway_required": bool(cfg.get("gateway_required", False)) if mode == "private_drive_gateway" else False,
        "gateway_state": gateway_state,
        "zero_drive_ui": cfg.get("zero_drive_ui", True) is not False,
        "github_media_storage": bool(cfg.get("github_media_storage", False)),
        "poster_quality": str(cfg.get("poster_quality") or "high"),
        "motion_preview": cfg.get("motion_preview", True) is not False,
        "billing_required": bool(cfg.get("billing_required", False)),
        "mandatory_paid_infrastructure": bool(cfg.get("mandatory_paid_infrastructure", False)),
        "public_access_policy": str(cfg.get("public_access_policy") or "anyone-reader-only"),
    }


def _gateway_media_url(settings: dict[str, Any], media_id: str, kind: str = "media") -> str:
    base = _media_delivery_config(settings).get("public_base_url") or ""
    media_id = quote(str(media_id or "").strip(), safe="")
