def _compact_public_css(text: str) -> str:
    """Shrink published CSS without changing the canonical source file.

    The root index and 404 embed the stylesheet while route shells share the
    asset. Compacting only the exported representation keeps GitHub transport
    budgets stable as editor-facing customization grows.
    """
    compact = re.sub(r"/\*.*?\*/", "", str(text or ""), flags=re.DOTALL)
    compact = re.sub(r"\s+", " ", compact)
    compact = re.sub(r"\s*([{}:;,>])\s*", r"\1", compact)
    return compact.strip()


def _compact_public_js(text: str) -> str:
    """Shrink only transport-safe JavaScript trivia.

    Keep the canonical source readable and avoid risky token minification.  We
    remove only full-line ``//`` comments and redundant blank lines, which is
    syntax-neutral for the StudioFrame public bundle and gives route-scale
    budgets enough headroom as new registries/features are added.
    """
    rows = []
    for line in str(text or "").splitlines():
        if line.lstrip().startswith("//"):
            continue
        if not line.strip():
            continue
        # Leading indentation is transport trivia while line boundaries remain
        # intact, preserving automatic-semicolon-insertion behavior.
        rows.append(line.strip())
    return "\n".join(rows).strip() + "\n"



