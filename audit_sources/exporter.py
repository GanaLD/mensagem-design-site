def _compose_public_site_template() -> str:
    """Compose the R2.2 modular public HTML without changing runtime IDs/contracts.

    `templates/site_index.html` remains a compatibility snapshot for older tools.
    New builds consume pages/home.html + explicit section/component fragments.
    """
    page = template_path("pages/home.html")
    if not page.is_file():
        return template_path("site_index.html").read_text(encoding="utf-8")
    output = page.read_text(encoding="utf-8")
    for token, relative in R22_PUBLIC_TEMPLATE_FRAGMENTS.items():
        fragment = template_path(relative)
        if not fragment.is_file():
            raise FileNotFoundError(f"R2.2 public template fragment missing: {relative}")
        output = output.replace(token, fragment.read_text(encoding="utf-8"))
    unresolved = sorted(set(re.findall(r"__PB_(?:COMPONENT|SECTION)_[A-Z0-9_]+__", output)))
    if unresolved:
        raise RuntimeError("R2.2 public template contains unresolved fragments: " + ", ".join(unresolved))
    return output

