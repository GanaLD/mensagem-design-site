def _write_bundle(site_dir: Path, manifest: dict[str, Any], settings: dict[str, Any], asset_registry: dict[str, Any] | None = None) -> None:
    _assert_public_video_contract(manifest)
    site_dir.mkdir(parents=True, exist_ok=True)
    (site_dir / "data").mkdir(parents=True, exist_ok=True)
    _copy_public_assets(site_dir, manifest)
    registries = _ensure_r22_public_registries(manifest)
    _write_r22_registry_files(site_dir, registries)
    asset_registry = asset_registry if isinstance(asset_registry, dict) else {"schema_version":1,"owner":"assets.registry","summary":{"total":0,"drive":0,"local":0,"failed":0,"types":{}},"items":[]}
    asset_health = registry_health(asset_registry)
    artifact_asset_registry = copy.deepcopy(asset_registry)
    artifact_asset_registry.pop("generated_at", None)
    (site_dir / "data" / "assets.json").write_text(json.dumps(artifact_asset_registry, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (site_dir / "data" / "asset-health.json").write_text(json.dumps(asset_health, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    manifest["asset_registry"] = {"owner":"assets.registry","file":"data/assets.json","health_file":"data/asset-health.json","summary":copy.deepcopy(asset_registry.get("summary") or {}),"health":copy.deepcopy(asset_health)}
    payload = json.dumps(manifest, ensure_ascii=False, indent=2)
    compact_payload = json.dumps(manifest, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    (site_dir / "data" / PUBLIC_DATA_FILENAME).write_text(payload, encoding="utf-8")

    route_template = _compose_public_site_template()
    site_css = _compact_public_css((resource_root() / "public_assets" / "site.css").read_text(encoding="utf-8"))
    site_js = _compact_public_js((resource_root() / "public_assets" / "site.js").read_text(encoding="utf-8"))
    # _copy_public_assets() intentionally copies canonical sources first; the
    # published CSS/JS assets are then replaced by transport-safe compact forms.
    (site_dir / "assets" / "site.css").write_text(site_css, encoding="utf-8", newline="\n")
    (site_dir / "assets" / "site.js").write_text(site_js, encoding="utf-8", newline="\n")
    route_map = seo_route_lookup(manifest)
    site_name = str((manifest.get("identity") or {}).get("studio_name") or "Mensagem Studio")

    # Root remains self-contained for offline opening. Its metadata is the actual
    # Home SEO, rather than a generic title shared by every route.
    home_meta = route_map.get("") or ((manifest.get("seo") or {}).get("home") or {})
    index = _apply_seo_head(route_template, home_meta, site_name=site_name)
    # Keep the root offline-capable without duplicating the already emitted
    # CSS and JS inside index.html. Relative assets work over file:// and HTTP(S);
    # only the manifest remains inline as the offline data fallback.
    index = (index
        .replace('<style>__PB_SITE_CSS__</style>', '<link rel="stylesheet" href="./assets/site.css?v=' + quote(str(BUILD_ID or APP_VERSION), safe='') + '">')
        .replace("__PB_MANIFEST_JSON__", compact_payload)
        .replace('<script>__PB_SITE_JS__</script>', '<script src="./assets/site.js?v=' + quote(str(BUILD_ID or APP_VERSION), safe='') + '"></script>'))
    (site_dir / "index.html").write_text(index, encoding="utf-8", newline="\n")

    # 404 is deliberately noindex. It uses the same shared public bundle as
    # generated route shells, avoiding a second full copy of CSS/JS/manifest.
    not_found = dict(home_meta)
    not_found.update({"title": f"Página não encontrada | {site_name}", "description":"", "canonical": str((manifest.get("seo") or {}).get("base_url") or "").rstrip("/") + "/404.html", "robots":"noindex,nofollow", "index":False, "follow":False, "og_type":"website"})
    html_404 = _apply_seo_head(route_template, not_found, site_name=site_name)
    html_404 = (html_404
        .replace('<style>__PB_SITE_CSS__</style>', '<script>window.__PB_ASSET_BASE__="/";</script><link rel="stylesheet" href="/assets/site.css?v=' + quote(str(BUILD_ID or APP_VERSION), safe='') + '">')
        .replace('<script>window.__PB_PUBLIC_DATA__=__PB_MANIFEST_JSON__;</script>', '')
        .replace('<script>__PB_SITE_JS__</script>', '<script src="/assets/site.js?v=' + quote(str(BUILD_ID or APP_VERSION), safe='') + '"></script>'))
    (site_dir / "404.html").write_text(html_404, encoding="utf-8", newline="\n")

    # Every resolved public SEO route receives a real thin HTML document. The
    # content remains shared through site.js/portfolio.json, but crawlers see the
    # route-specific title, description, canonical, OG and JSON-LD immediately.
    for full_path, route_meta in sorted(route_map.items()):
        if not full_path:
            continue
        route_dir = site_dir.joinpath(*full_path.split("/"))
        route_dir.mkdir(parents=True, exist_ok=True)
        (route_dir / "index.html").write_text(_route_shell(route_template, full_path, route_meta, site_name=site_name), encoding="utf-8", newline="\n")

    seo = manifest.get("seo") if isinstance(manifest.get("seo"), dict) else {}
    sitemap_urls = [str(url).strip() for url in seo.get("sitemap") or [] if str(url or "").strip()]
    sitemap_rows = ['<?xml version="1.0" encoding="UTF-8"?>','<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    sitemap_rows.extend(f"  <url><loc>{escape(url, quote=False)}</loc></url>" for url in sitemap_urls)
    sitemap_rows.append('</urlset>')
    (site_dir / "sitemap.xml").write_text("\n".join(sitemap_rows) + "\n", encoding="utf-8")
    base_url = str(seo.get("base_url") or "").rstrip("/")
    robots_rows = ["User-agent: *", "Allow: /"]
    if seo.get("robots_enabled") is not False and seo.get("sitemap_enabled") is not False and base_url:
        robots_rows.append(f"Sitemap: {base_url}/sitemap.xml")
    (site_dir / "robots.txt").write_text("\n".join(robots_rows) + "\n", encoding="utf-8")
    (site_dir / "data" / "seo-report.json").write_text(json.dumps({
        "version": seo.get("version"),
        "owner": seo.get("owner"),
        "base_url": base_url,
        "summary": seo.get("summary") or {},
        "diagnostics": seo.get("diagnostics") or [],
        "routes": [{k: row.get(k) for k in ("path","kind","canonical","index","robots","schema_type")} for row in (seo.get("routes") or []) if isinstance(row, dict)],
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    llms_path = site_dir / "llms.txt"
    if seo.get("llms_txt_enabled") is True:
        llms_path.write_text(llms_discovery_text(seo, site_name=site_name), encoding="utf-8")
    elif llms_path.exists():
        llms_path.unlink()

    (site_dir / ".nojekyll").write_text("", encoding="utf-8")
    public_domain = str(settings.get("publication", {}).get("public_domain") or "").strip()
    if public_domain:
        (site_dir / "CNAME").write_text(public_domain + "\n", encoding="utf-8")

    _write_build_manifest(site_dir, manifest)

    required = [site_dir / "index.html", site_dir / "404.html", site_dir / "assets" / "site.css", site_dir / "assets" / "site.js", site_dir / "data" / PUBLIC_DATA_FILENAME, site_dir / "data" / "build-manifest.json", site_dir / "data" / "seo-report.json", site_dir / "data" / "assets.json", site_dir / "data" / "asset-health.json", site_dir / "data" / "forms.json", site_dir / "data" / "forms-health.json", site_dir / "data" / "immersive.json", site_dir / "data" / "immersive-health.json", site_dir / "assets" / "immersive" / "immersive-v31.js", site_dir / "sitemap.xml", site_dir / "robots.txt"]
    missing = [path.name for path in required if not path.exists()]
    if missing:
        raise RuntimeError("Build incompleto: " + ", ".join(missing))
    for path in site_dir.rglob("*"):
        if path.is_file() and path.suffix in {".html", ".css", ".js", ".json"}:
            lowered = path.read_text(encoding="utf-8", errors="ignore").casefold()
            found = [marker for marker in FORBIDDEN if marker in lowered]
            if found:
                raise RuntimeError(f"Arquivo público {path.name} contém marcadores proibidos: {', '.join(found)}")

def inspect_site_bundle(site_dir: Path, *, expected_projects: int | None = None) -> dict[str, Any]:
    """Validate the exact static bundle that will be served/published."""
    site_dir = Path(site_dir).resolve()
    required = [
        site_dir / "index.html",
        site_dir / "404.html",
        site_dir / "assets" / "site.css",
        site_dir / "assets" / "site.js",
        site_dir / "assets" / "motion" / "vendor" / "gsap" / "gsap.min.js",
        site_dir / "assets" / "motion" / "vendor" / "motion" / "motion.js",
        site_dir / "assets" / "motion" / "vendor" / "three" / "three.module.min.js",
        site_dir / "assets" / "motion" / "vendor" / "three" / "three.core.min.js",
        site_dir / "data" / PUBLIC_DATA_FILENAME,
        site_dir / "data" / "projects.json",
        site_dir / "data" / "pages.json",
        site_dir / "data" / "sections.json",
        site_dir / "data" / "routes.json",
        site_dir / "data" / "assets.json",
        site_dir / "data" / "asset-health.json",
        site_dir / "data" / "build-manifest.json",
        site_dir / "data" / "seo-report.json",
        site_dir / "sitemap.xml",
        site_dir / "robots.txt",
    ]
    missing = [str(path.relative_to(site_dir)) for path in required if not path.is_file()]
    if missing:
        raise RuntimeError("Build público incompleto: " + ", ".join(missing))

    manifest_path = site_dir / "data" / PUBLIC_DATA_FILENAME
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    projects = list(manifest.get("projects") or [])
    if expected_projects is not None and len(projects) != int(expected_projects):
        raise RuntimeError(
            f"Build público inconsistente: esperava {expected_projects} projetos visíveis, "
            f"mas portfolio.json contém {len(projects)}."
        )
    if not isinstance(manifest.get("categories"), list):
        raise RuntimeError("portfolio.json inválido: categories ausente.")

    build_meta = json.loads((site_dir / "data" / "build-manifest.json").read_text(encoding="utf-8"))
    if build_meta.get("format") != "studioframe-public-build-v2":
        raise RuntimeError("build-manifest.json incompatível ou ausente.")
    expected_files = build_meta.get("files") or {}
    actual_files = {path.relative_to(site_dir).as_posix() for path in site_dir.rglob("*") if path.is_file() and path != site_dir / "data" / "build-manifest.json"}
    if set(expected_files) != actual_files:
        missing_files = sorted(set(expected_files) - actual_files)
        extra_files = sorted(actual_files - set(expected_files))
        raise RuntimeError(f"Build incremental divergiu do manifesto: ausentes={missing_files[:5]} extras={extra_files[:5]}.")
    for relative, item in expected_files.items():
        path = site_dir.joinpath(*Path(relative).parts)
        expected_size = (item or {}).get("bytes")
        if not path.is_file() or expected_size is None or path.stat().st_size != int(expected_size):
            raise RuntimeError(f"Build incremental inconsistente em {relative}.")
        if _sha256_file(path) != str((item or {}).get("sha256") or ""):
            raise RuntimeError(f"Hash do build divergiu em {relative}.")
    canonical_files = json.dumps(expected_files, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()
    if hashlib.sha256(canonical_files).hexdigest() != str(build_meta.get("bundle_sha256") or ""):
        raise RuntimeError("Hash global do build-manifest.json divergiu.")

    seo = manifest.get("seo") if isinstance(manifest.get("seo"), dict) else {}
    seo_routes = [row for row in seo.get("routes") or [] if isinstance(row, dict)]
    expected_routes = [str(row.get("path") or "").strip("/") for row in seo_routes if str(row.get("path") or "").strip("/")]
    for route in expected_routes:
        shell = site_dir.joinpath(*route.split("/"), "index.html")
        if not shell.is_file():
            raise RuntimeError(f"Rota pública sem HTML: /{route}/")
        shell_text = shell.read_text(encoding="utf-8", errors="replace")
        if "data-studioframe-route-shell" not in shell_text or "__PB_MANIFEST_JSON__" in shell_text:
            raise RuntimeError(f"Rota /{route}/ não usa o shell compartilhado V7.10.0.")
        if '<link rel="canonical"' not in shell_text:
            raise RuntimeError(f"Rota /{route}/ sem metadata SEO individual.")
        if seo.get("social_cards_enabled") is not False and 'property="og:title"' not in shell_text:
            raise RuntimeError(f"Rota /{route}/ sem Open Graph com social cards habilitados.")
        if seo.get("structured_data_enabled") is not False and 'application/ld+json' not in shell_text:
            raise RuntimeError(f"Rota /{route}/ sem JSON-LD com dados estruturados habilitados.")
        if shell.stat().st_size > 128 * 1024:
            raise RuntimeError(f"Rota /{route}/ excedeu 128 KiB e voltou a duplicar o aplicativo.")

    sitemap_text = (site_dir / "sitemap.xml").read_text(encoding="utf-8", errors="replace")
    expected_sitemap = [str(row.get("canonical") or "") for row in seo_routes if row.get("index") and str(row.get("canonical") or "")] if seo.get("sitemap_enabled") is not False else []
    if len(expected_sitemap) != len(set(expected_sitemap)):
        raise RuntimeError("SEO inválido: sitemap possui canonical duplicado na origem.")
    for url in expected_sitemap:
        if f"<loc>{url}</loc>" not in sitemap_text:
            raise RuntimeError(f"sitemap.xml não contém rota indexável: {url}")
    for row in seo_routes:
        url = str(row.get("canonical") or "")
        if row.get("index") is False and url and f"<loc>{url}</loc>" in sitemap_text:
            raise RuntimeError(f"Rota noindex apareceu no sitemap: {url}")
    robots_text = (site_dir / "robots.txt").read_text(encoding="utf-8", errors="replace")
    base_url = str(seo.get("base_url") or "").rstrip("/")
    if seo.get("robots_enabled") is not False and seo.get("sitemap_enabled") is not False and base_url and f"Sitemap: {base_url}/sitemap.xml" not in robots_text:
        raise RuntimeError("robots.txt não aponta para o sitemap público.")
    seo_report = json.loads((site_dir / "data" / "seo-report.json").read_text(encoding="utf-8"))
    if seo_report.get("owner") != "site_builder.seo":
        raise RuntimeError("SEO report não aponta para o owner canônico site_builder.seo.")
    if seo.get("llms_txt_enabled") is True and not (site_dir / "llms.txt").is_file():
        raise RuntimeError("llms.txt habilitado, mas não foi gerado.")

    for project in projects:
        if not str(project.get("id") or ""):
            raise RuntimeError("portfolio.json contém projeto sem id.")
        if project.get("type") == "image" and not (project.get("media_url") or project.get("media_candidates")):
            raise RuntimeError(f"Imagem sem URL pública no build: {project.get('title') or project.get('id')}")
        if project.get("type") == "pdf" and not (project.get("preview_url") or project.get("preview_candidates") or project.get("media_url")):
            raise RuntimeError(f"PDF sem URL pública no build: {project.get('title') or project.get('id')}")
        if project.get("type") == "video":
            # V7.4: public video must stay inside the StudioFrame player while the
            # bytes may come directly from the anonymous read-only Drive endpoints.
            if project.get("external_url"):
                raise RuntimeError(f"ADR-003 violada: vídeo expôs navegação externa: {project.get('title') or project.get('id')}")
            candidates = [
                str(project.get("media_url") or ""), str(project.get("preview_url") or ""),
                *(str(v) for v in (project.get("media_candidates") or [])),
                *(str(v) for v in (project.get("preview_candidates") or [])),
            ]
            candidates = [v for v in candidates if v]
            if not candidates:
                raise RuntimeError(f"Vídeo sem byte-source pública no build: {project.get('title') or project.get('id')}")
            for candidate in candidates:
                lowered = candidate.casefold()
                if any(token in lowered for token in ("drive.google.com/file/", "drive.google.com/open", "webviewlink", "accounts.google.com")):
                    raise RuntimeError(f"ADR-003 violada: Drive UI/navegação exposta no build: {candidate}")
                if not _public_video_deferred_candidate_allowed(candidate):
                    raise RuntimeError(f"ADR-003/V7.4 violada: candidato de vídeo não é byte-source Drive permitida: {candidate}")

    return {
        "ok": True,
        "path": str(site_dir),
        "manifest": str(manifest_path),
        "projects": len(projects),
        "categories": len(manifest.get("categories") or []),
        "bytes": int((build_meta.get("stats") or {}).get("bytes") or 0),
        "bundle_sha256": str(build_meta.get("bundle_sha256") or ""),
        "route_shells": len(expected_routes),
        "files": [str(path.relative_to(site_dir)) for path in required],
    }


def _atomic_replace(staging: Path, target: Path) -> None:
    """Atomically promote a fully validated bundle without in-place overwrite.

    Windows can deny renames while Explorer, antivirus or an older StudioFrame
    process still has a handle inside ``exports/site``.  The previous fallback
    copied files over the locked directory and could both fail publication and
    leave a mixed old/new tree.  V7.12.3 never mutates a locked target in place.
    Either the directory swap succeeds or the last valid target is preserved.
    """
    backup = target.with_name(target.name + ".previous")
    # Only remove a stale backup when the canonical target is present. If the
    # target is absent, a previous directory may be the only recoverable build.
    if target.exists():
        shutil.rmtree(backup, ignore_errors=True)
    moved_old = False
    try:
        if target.exists():
            target.replace(backup)
            moved_old = True
        staging.replace(target)
    except OSError as exc:
        # If the old target was moved successfully but promotion failed, restore
        # it before surfacing the error. Never copy file-by-file into target.
        if moved_old and backup.exists() and not target.exists():
            try:
                backup.replace(target)
                moved_old = False
            except OSError as restore_exc:
                raise OSError(
                    f"Falha ao promover o build e ao restaurar o site anterior. "
                    f"Backup preservado em {backup}: {restore_exc}"
                ) from exc
        raise
    else:
        if backup.exists():
            shutil.rmtree(backup, ignore_errors=True)


def refresh_public_site_from_build(source: Path, target: Path | None = None) -> dict[str, Any]:
    """Best-effort refresh of the local preview from an immutable build.

    Failure to refresh ``exports/site`` must never invalidate a publishable
    bundle.  The caller receives diagnostics and may continue to GitHub using
    ``source``.  The last valid local preview remains untouched on failure.
    """
    source = Path(source).resolve()
    target = Path(target).resolve() if target else public_site_dir().resolve()
    result = {"ok": False, "source": str(source), "target": str(target), "message": ""}
    try:
        inspect_site_bundle(source)
        target.parent.mkdir(parents=True, exist_ok=True)
        ready = target.parent / f".{target.name}.ready-{os.getpid()}-{__import__('time').time_ns()}"
        shutil.rmtree(ready, ignore_errors=True)
        shutil.copytree(source, ready)
        _atomic_replace(ready, target)
        result.update({"ok": True, "message": "Preview local atualizado a partir do build imutável."})
        return result
    except Exception as exc:
        try:
            if 'ready' in locals(): shutil.rmtree(ready, ignore_errors=True)
        except Exception:
            pass
        result["message"] = f"Preview local mantido na versão anterior porque o Windows bloqueou a pasta: {exc}"
        write_log("build", result["message"])
        return result

def _manifest_file_diff(previous: dict[str, Any], current: dict[str, Any]) -> dict[str, Any]:
    old_files = previous.get("files") if isinstance(previous, dict) else {}
    new_files = current.get("files") if isinstance(current, dict) else {}
    old_files = old_files if isinstance(old_files, dict) else {}
    new_files = new_files if isinstance(new_files, dict) else {}
    changed = sorted(name for name, meta in new_files.items() if (old_files.get(name) or {}).get("sha256") != (meta or {}).get("sha256"))
    removed = sorted(name for name in old_files if name not in new_files)
    unchanged = sorted(name for name, meta in new_files.items() if name in old_files and (old_files.get(name) or {}).get("sha256") == (meta or {}).get("sha256"))
    return {"changed_files": changed, "removed_files": removed, "unchanged_files": unchanged, "changed_count": len(changed), "removed_count": len(removed), "unchanged_count": len(unchanged)}


def export_site(
    catalog: dict[str, Any],
    settings: dict[str, Any],
    strict: bool = True,
    *,
    target_dir: Path | None = None,
    media_provider: Any | None = None,
    progress_callback: Any | None = None,
) -> dict[str, Any]:
    """Generate the static site or prepare a publishable build.

    Local generation and remote publication are deliberately independent:
    - strict=False: NEVER performs network/public-link validation. It writes the
      HTML immediately from the catalog already loaded in the editor.
    - strict=True: validates anonymous public delivery first and only then builds
      the exact bundle eligible for GitHub publication.
    """
    if strict:
        # V7.4 zero-cost contract: the root Drive folder must be anonymous-reader
        # only, then every visible media asset is probed through direct public byte
        # candidates before the GitHub bundle can be published. No paid gateway,
        # card/billing or media blob upload is required.
        access = validate_drive_public_readonly_access(media_provider)
        if not access.get("ok"):
            return {
                "ok": False, "html_generated": False, "publication_ready": False,
                "message": f"Publicação bloqueada: {access.get('message') or 'permissão pública do Drive inválida.'}",
                "validation": access, "drive_public_access": access,
            }
        extra_ids = _editorial_media_ids(settings) | _seo_media_ids(settings)
        validation = validate_public_links(catalog, timeout=20, max_workers=8, extra_media_ids=extra_ids)
        validation["drive_public_access"] = copy.deepcopy(access)
        if not validation.get("ok"):
            first = (validation.get("failures") or [{}])[0]
            name = str(first.get("name") or first.get("file_id") or "mídia")
            reason = str(first.get("reason") or "fonte pública indisponível")
            return {
                "ok": False, "html_generated": False, "publication_ready": False,
                "message": f"Publicação bloqueada: a mídia pública do Drive não passou na validação ({name}: {reason}).",
                "validation": validation, "drive_public_access": access,
            }
        export_catalog = apply_public_selections(catalog, validation.get("selections") or {})
        publication_ready = True
    else:
        # Generating the product artifact must not depend on Google/GitHub/network
        # state. Use the durable public URL candidates already present in the
        # synchronized catalog. The separate validation/publish actions determine
        # whether those URLs are actually reachable by anonymous visitors.
        validation = {
            "ok": False,
            "checked": 0,
            "valid": 0,
            "invalid": 0,
            "failures": [],
            "selections": {},
            "mode": "not-run-during-local-html-generation",
            "message": "Validação pública não executada durante Gerar HTML.",
        }
        export_catalog = copy.deepcopy(catalog)
        publication_ready = False

    manifest = build_manifest(export_catalog, settings, editor=False)
    asset_registry = build_asset_registry(export_catalog, settings, include_local=True)
    asset_health = registry_health(asset_registry)
    manifest["asset_registry"] = {"owner":"assets.registry","file":"data/assets.json","health_file":"data/asset-health.json","summary":copy.deepcopy(asset_registry.get("summary") or {}),"health":copy.deepcopy(asset_health)}
    manifest["publication_ready"] = publication_ready
    manifest["public_validation"] = {
        "checked": int(validation.get("checked") or 0),
        "valid": int(validation.get("valid") or 0),
        "invalid": int(validation.get("invalid") or 0),
        "mode": validation.get("mode", ""),
    }
    target = Path(target_dir).resolve() if target_dir else public_site_dir().resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    previous_build_meta: dict[str, Any] = {}
    previous_meta_path = target / "data" / "build-manifest.json"
    if previous_meta_path.is_file():
        try: previous_build_meta = json.loads(previous_meta_path.read_text(encoding="utf-8"))
        except Exception as exc: write_log("build", f"Manifesto anterior ignorado para diff: {exc}")

    with tempfile.TemporaryDirectory(prefix="portfolio-staging-", dir=str(target.parent)) as temporary:
        staging = Path(temporary) / "site"
        # V7.9.6.3 restores the original architecture: Drive owns full media;
        # GitHub receives only the static site plus small authenticated posters.
        # This keeps cards dependable without turning a portfolio deployment into
        # a 60+ MiB video upload that GitHub's REST JSON parser can reject.
        # V7.4 final zero-cost delivery: GitHub receives no portfolio media.
        # Drive remains media authority and the browser receives only read-only
        # byte endpoints; Drive Viewer/navigation remains forbidden. Historical
        # Gateway/materializer code stays available for audit/rollback only.
        poster_assets = {"hosted":0,"failed":0,"bytes":0,"mode":"drive-public-readonly-no-github-media"}
        video_assets = {"hosted":0,"optimized":0,"copied":0,"reused":0,"failed":0,"bytes":0,"items":[],"mode":"drive-public-readonly-no-github-media"}
        manifest["poster_assets"] = copy.deepcopy(poster_assets)
        manifest["video_assets"] = copy.deepcopy(video_assets)
        manifest["media_delivery"] = {**_media_delivery_config(settings), "authority":"google-drive", "public_delivery":"drive-public-readonly-bytes", "github_media_storage":False}
        # V7.10.0: resolve route-level SEO only after posters/full-media URLs are final.
        attach_seo_manifest(manifest, settings)
        if strict:
            delivery_cfg = _media_delivery_config(settings)
            publication_ready = bool(validation.get("ok"))
            manifest["publication_ready"] = publication_ready
            manifest["public_validation"] = {
                "checked": int(validation.get("checked") or 0),
                "valid": int(validation.get("valid") or 0),
                "invalid": int(validation.get("invalid") or 0),
                "mode": "drive-public-readonly-bytes",
                "code": "DRIVE_PUBLIC_BYTES_READY" if publication_ready else "DRIVE_PUBLIC_BYTES_FAILED",
                "warnings": copy.deepcopy(validation.get("warnings") or []),
                "failures": copy.deepcopy(validation.get("failures") or []),
                "drive_public_access": copy.deepcopy(validation.get("drive_public_access") or {}),
            }
            manifest["media_readiness"] = {
                "drive_media_authority": True,
                "drive_public_readonly": bool((validation.get("drive_public_access") or {}).get("public_reader")),
                "gateway_primary": False,
                "gateway_required": False,
                "github_media_storage": False,
                "drive_ui_public": False,
                "checked": int(validation.get("checked") or 0),
                "failed": int(validation.get("invalid") or 0),
                "playback_ready": publication_ready,
                "motion_preview_protected": True,
                "poster_quality_protected": True,
                "mandatory_paid_infrastructure": False,
            }
            write_log("build", f"V7.4 Drive public readonly readiness: acl=reader, checked={validation.get('checked',0)}, invalid={validation.get('invalid',0)}, DriveUI=forbidden, GitHubMedia=0, billing=0.")
        _write_bundle(staging, manifest, settings, asset_registry=asset_registry)
        expected_projects = len(manifest.get("projects") or [])
        staging_check = inspect_site_bundle(staging, expected_projects=expected_projects)
        if target_dir:
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(staging, target)
        else:
            ready = target.parent / f".{target.name}.ready-{os.getpid()}"
            shutil.rmtree(ready, ignore_errors=True)
            staging.replace(ready)
            _atomic_replace(ready, target)

    final_check = inspect_site_bundle(target, expected_projects=len(manifest.get("projects") or []))
    current_build_meta = json.loads((target / "data" / "build-manifest.json").read_text(encoding="utf-8"))
    build_diff = _manifest_file_diff(previous_build_meta, current_build_meta)
    generated_at = __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat()
    archive_path = ""
    history_build = {}
    if target_dir is None:
        archive_base = exports_dir() / "MensagemStudio_Portfolio_Site"
        archive_path = shutil.make_archive(str(archive_base), "zip", root_dir=target)
        history_build = archive_build(target, manifest)

    return {
        "ok": True,
        "html_generated": True,
        "publication_ready": publication_ready,
        "message": (
            "HTML final gerado e validado para publicação pública."
            if publication_ready
            else "HTML final gerado. Use Validar mídias/Prontidão antes de publicar."
        ),
        "path": str(target),
        "filename": "index.html",
        "manifest": str(target / "data" / PUBLIC_DATA_FILENAME),
        "build_manifest": str(target / "data" / "build-manifest.json"),
        "archive": str(archive_path) if archive_path else "",
        "history_build": history_build,
        "bundle_check": final_check,
        "staging_check": staging_check,
        "video_assets": video_assets,
        "poster_assets": poster_assets,
        "editorial_revision": str(manifest.get("editorial_revision") or ""),
        "build_revision": str(current_build_meta.get("build_revision") or ""),
        "build_id": BUILD_ID,
        "artifact_id": str(current_build_meta.get("artifact_id") or ""),
        "artifact_sha256": str(current_build_meta.get("artifact_sha256") or current_build_meta.get("bundle_sha256") or ""),
        "generated_at": generated_at,
        "build_diff": build_diff,
        "incremental": {"poster_reused_bytes": int(poster_assets.get("reused_bytes") or 0), "poster_downloaded_bytes": int(poster_assets.get("downloaded_bytes") or 0), "video_reused_bytes": int(video_assets.get("reused_bytes") or 0), "video_downloaded_bytes": int(video_assets.get("downloaded_bytes") or 0), "bundle_sha256": final_check.get("bundle_sha256", ""), "route_shells": int(final_check.get("route_shells") or 0), "changed_files": build_diff.get("changed_count", 0), "removed_files": build_diff.get("removed_count", 0)},
        "publication_bundle_policy": "v7.4-zero-cost-drive-public-readonly+zero-drive-ui+no-github-media+no-billing+shared-route-shells+incremental-github-blobs",
        "validation": validation,
    }


