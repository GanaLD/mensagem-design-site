def _materialize_poster_assets(
    site_dir: Path,
    manifest: dict[str, Any],
    media_provider: Any | None,
    *,
    max_file_bytes: int = 1536 * 1024,
    max_total_bytes: int = 18 * 1024 * 1024,
    reuse_dir: Path | None = None,
) -> dict[str, Any]:
    """Materialize stable authenticated poster bytes for visible/public media.

    The grid must not depend on anonymous Google Drive thumbnail permissions.
    One local poster per media id is enough for cards, hero fallback and viewer
    fallback while the full-resolution Drive URL remains available as an upgrade.
    """
    if media_provider is None or not hasattr(media_provider, "thumbnail_data"):
        stats = {"hosted": 0, "optimized": 0, "copied": 0, "reused": 0, "failed": 0, "skipped": 0, "bytes": 0, "reused_bytes": 0, "downloaded_bytes": 0, "optimized_bytes": 0, "items": [], "fallbacks": [], "mode": "provider-unavailable"}
        manifest["poster_assets"] = stats
        return stats

    media_records: list[dict[str, Any]] = []
    def collect(value: Any) -> None:
        if isinstance(value, dict):
            if str(value.get("type") or "") in {"image", "video", "pdf"} and (
                str(value.get("id") or "") or str(value.get("cover_media_id") or "")
            ):
                media_records.append(value)
            for child in value.values(): collect(child)
        elif isinstance(value, list):
            for child in value: collect(child)
    collect(manifest)

    # Resolve real media ids first. Navigation cards use folder ids but copy the
    # chosen cover URLs; match those URLs back to a real media record.
    by_id: dict[str, list[dict[str, Any]]] = {}
    navigation_records: list[dict[str, Any]] = []
    for record in media_records:
        if record.get("navigation_kind"):
            navigation_records.append(record)
            continue
        media_id = str(record.get("id") or "").strip()
        if media_id:
            by_id.setdefault(media_id, []).append(record)

    url_to_id: dict[str, str] = {}
    for media_id, records in by_id.items():
        for record in records:
            for value in (
                record.get("thumbnail_url"), record.get("media_url"), record.get("preview_url"),
                *(record.get("thumbnail_candidates") or []), *(record.get("media_candidates") or []), *(record.get("preview_candidates") or []),
            ):
                if value: url_to_id.setdefault(str(value), media_id)
    for record in navigation_records:
        source_id = str(record.get("cover_media_id") or "").strip()
        if source_id not in by_id:
            source_id = next((url_to_id.get(str(value)) for value in (
                record.get("thumbnail_url"), record.get("media_url"), record.get("preview_url"),
                *(record.get("thumbnail_candidates") or []), *(record.get("media_candidates") or []), *(record.get("preview_candidates") or []),
            ) if value and url_to_id.get(str(value))), "")
        if source_id and source_id in by_id:
            by_id[source_id].append(record)

    # V7.9.6.4: a finite poster budget must always favor what the visitor can
    # actually see first: project/navigation covers, Hero assets and videos.
    # Previously the recursive manifest order could spend the whole budget on
    # deep gallery items and leave visible cards without a stable local poster.
    priority_ids: set[str] = set()
    for project in manifest.get("projects") or []:
        if not isinstance(project, dict): continue
        cover_id = str(project.get("cover_media_id") or "").strip()
        if cover_id: priority_ids.add(cover_id)
        if str(project.get("type") or "") in {"image","video","pdf"} and str(project.get("id") or "").strip():
            priority_ids.add(str(project.get("id")))
    for node in manifest.get("navigation_nodes") or []:
        if isinstance(node, dict) and str(node.get("cover_media_id") or "").strip(): priority_ids.add(str(node.get("cover_media_id")))
    for media_id in (manifest.get("hero_assets") or {}).keys(): priority_ids.add(str(media_id))
    ordered_media_ids = sorted(
        by_id.keys(),
        key=lambda media_id: (
            0 if media_id in priority_ids else 1,
            0 if any(str(record.get("type") or "") == "video" for record in by_id.get(media_id, [])) else 1,
            media_id,
        ),
    )

    poster_dir = site_dir / "assets" / "posters"
    poster_dir.mkdir(parents=True, exist_ok=True)
    reuse_dir = Path(reuse_dir).resolve() if reuse_dir else None
    previous_items: dict[str, dict[str, Any]] = {}
    if reuse_dir and (reuse_dir / "data" / "build-manifest.json").is_file():
        try:
            previous_meta = json.loads((reuse_dir / "data" / "build-manifest.json").read_text(encoding="utf-8"))
            previous_items = {str(item.get("id") or ""): item for item in ((previous_meta.get("poster_assets") or {}).get("items") or []) if isinstance(item, dict)}
        except Exception as exc:
            write_log("build", f"Cache incremental de posters ignorado: {exc}")

    hosted: list[dict[str, Any]] = []
    skipped: list[dict[str, str]] = []
    total = reused_bytes = downloaded_bytes = 0

    def bind(records: list[dict[str, Any]], asset_url: str) -> None:
        for record in records:
            previous = _unique([str(record.get("thumbnail_url") or ""), *[str(v) for v in (record.get("thumbnail_candidates") or [])]])
            record["thumbnail_url"] = asset_url
            record["thumbnail_candidates"] = _unique([asset_url, *previous])
            record["hosted_poster"] = True

    for media_id in ordered_media_ids:
        records = by_id[media_id]
        if total >= max_total_bytes: skipped.append({"id": media_id, "reason": "limite total de posters"}); continue
        modified_time = next((str(record.get("modified_time") or "") for record in records if record.get("modified_time")), "")
        previous = previous_items.get(media_id) or {}
        previous_relative = str(previous.get("path") or "").strip("/")
        previous_path = reuse_dir.joinpath(*previous_relative.split("/")) if reuse_dir and previous_relative else None
        can_reuse = bool(previous_path and previous_path.is_file() and int(previous.get("bytes") or 0) == previous_path.stat().st_size)
        if modified_time and previous.get("modified_time") and previous.get("modified_time") != modified_time: can_reuse = False
        if can_reuse and previous.get("sha256") and _sha256_file(previous_path) != str(previous.get("sha256")): can_reuse = False
        if can_reuse and previous_path.stat().st_size <= max_file_bytes and total + previous_path.stat().st_size <= max_total_bytes:
            target = poster_dir / previous_path.name
            shutil.copy2(previous_path, target)
            size = target.stat().st_size; total += size; reused_bytes += size
            asset_url = f"assets/posters/{target.name}"; bind(records, asset_url)
            hosted.append({"id":media_id,"path":asset_url,"bytes":size,"mime":str(previous.get("mime") or "image/jpeg"),"modified_time":modified_time,"sha256":_sha256_file(target)})
            continue
        try:
            data, ctype, _headers = media_provider.thumbnail_data(media_id)
            if not data: raise ValueError("thumbnail vazio")
            if len(data) > max_file_bytes: raise ValueError(f"poster com {len(data)} bytes excede {max_file_bytes}")
            if total + len(data) > max_total_bytes: raise ValueError("poster excede orçamento total")
            ctype = str(ctype or "image/jpeg").split(";",1)[0].casefold()
            suffix = ".png" if "png" in ctype else ".webp" if "webp" in ctype else ".gif" if "gif" in ctype else ".jpg"
            safe_id = re.sub(r"[^a-zA-Z0-9_-]+", "-", media_id).strip("-") or "media"
            target = poster_dir / f"{safe_id}{suffix}"
            target.write_bytes(data); size=len(data); total += size; downloaded_bytes += size
            asset_url=f"assets/posters/{target.name}"; bind(records, asset_url)
            hosted.append({"id":media_id,"path":asset_url,"bytes":size,"mime":ctype,"modified_time":modified_time,"sha256":_sha256_file(target)})
        except Exception as exc:
            skipped.append({"id":media_id,"reason":str(exc)})
            write_log("build", f"Poster {media_id} não materializado: {exc}")

    stats={"hosted":len(hosted),"skipped":len(skipped),"bytes":total,"reused_bytes":reused_bytes,"downloaded_bytes":downloaded_bytes,"items":hosted,"fallbacks":skipped,"mode":"priority-authenticated-stable-posters-v7964"}
    manifest["poster_assets"] = stats
    return stats


def _materialize_video_assets(
    site_dir: Path,
    manifest: dict[str, Any],
    media_provider: Any | None,
    *,
    max_source_bytes: int = 1024 * 1024 * 1024,
    max_total_bytes: int = 320 * 1024 * 1024,
    direct_file_bytes: int = 7 * 1024 * 1024,
    preferred_target_bytes: int = 6 * 1024 * 1024,
    reuse_dir: Path | None = None,
    max_file_bytes: int | None = None,
    chunk_bytes: int | None = None,
    progress_callback: Any | None = None,
) -> dict[str, Any]:
    """Publish browser-friendly videos without letting originals exhaust the build.

    V7.12.8 keeps same-origin playback and makes every generated media file safe for the REST transport:
    * already-small MP4 files can be copied directly;
    * larger/incompatible sources are converted to H.264/AAC MP4 with faststart;
    * every derivative targets about 6 MiB and is capped below 7 MiB, keeping the Base64/JSON REST request safely bounded;
    * the aggregate video budget is 320 MiB, leaving substantial headroom for the
      rest of the site and the publisher's absolute safety guard;
    * derivatives are cached in LOCALAPPDATA by Drive id + modifiedTime + profile.
    """
    # Backward-compatible keyword aliases used by older regression tests and
    # integrations. V7.12.6 no longer emits chunks, but accepting the old names
    # prevents API breakage while mapping them to the new safe policy.
    if max_file_bytes is not None:
        max_source_bytes=max(1024,int(max_file_bytes))
        direct_file_bytes=min(direct_file_bytes,max(1024,int(max_file_bytes)))
        preferred_target_bytes=min(preferred_target_bytes,max(1024,int(max_file_bytes)))
    _ = chunk_bytes
    if media_provider is None:
        stats={"hosted":0,"skipped":0,"bytes":0,"items":[],"optimized":0,"mode":"cache-first-rest-safe-video-v7128"}
        manifest["video_assets"]=stats
        return copy.deepcopy(stats)

    video_records: list[dict[str, Any]] = []
    def collect(value: Any) -> None:
        if isinstance(value, dict):
            if str(value.get("type") or "") == "video" and str(value.get("id") or ""):
                video_records.append(value)
            for child in value.values(): collect(child)
        elif isinstance(value, list):
            for child in value: collect(child)
    collect(manifest)

    by_id: dict[str, list[dict[str, Any]]] = {}
    navigation_records: list[dict[str, Any]] = []
    for record in video_records:
        if record.get("navigation_kind"): navigation_records.append(record)
        else: by_id.setdefault(str(record["id"]), []).append(record)
    url_to_id: dict[str, str] = {}
    for media_id, records in by_id.items():
        for record in records:
            for value in (record.get("media_url"), record.get("preview_url"), *(record.get("media_candidates") or []), *(record.get("preview_candidates") or [])):
                if value: url_to_id.setdefault(str(value), media_id)
    for record in navigation_records:
        source_id = next((url_to_id.get(str(value)) for value in (record.get("media_url"), record.get("preview_url"), *(record.get("media_candidates") or []), *(record.get("preview_candidates") or [])) if value and url_to_id.get(str(value))), "")
        if source_id: by_id.setdefault(source_id, []).append(record)

    media_dir = site_dir / "assets" / "media"; media_dir.mkdir(parents=True, exist_ok=True)
    # Do not emit new video-chunks in V7.12.6. Old folders can only exist in a
    # previous build and are never copied forward by this function.
    hosted: list[dict[str, Any]]=[]; skipped: list[dict[str, str]]=[]
    total=reused_bytes=downloaded_bytes=optimized_bytes=0
    reuse_dir=Path(reuse_dir).resolve() if reuse_dir else None
    previous_items: dict[str, dict[str, Any]]={}
    if reuse_dir and (reuse_dir/"data"/"build-manifest.json").is_file():
        try:
            previous_meta=json.loads((reuse_dir/"data"/"build-manifest.json").read_text(encoding="utf-8"))
            previous_items={str(item.get("id") or ""):item for item in ((previous_meta.get("video_assets") or {}).get("items") or []) if isinstance(item,dict) and str(item.get("id") or "")}
        except Exception as exc: write_log("build",f"Cache incremental de vídeo web ignorado: {exc}")

    def bind(records: list[dict[str, Any]], asset_url: str, *, optimized: bool) -> None:
        for record in records:
            # Stage 5.5.1 / ADR-021: the same-origin derivative is authoritative.
            # Keep only the narrow Drive byte-delivery allowlist as secondary
            # browser fallback; Viewer/navigation URLs never survive here.
            previous_candidates=_unique([str(record.get("media_url") or ""), *[str(v) for v in (record.get("media_candidates") or [])]])
            safe_fallbacks=[value for value in previous_candidates if value and value!=asset_url and _public_video_deferred_candidate_allowed(value)]
            record["media_url"]=asset_url; record["media_candidates"]=_unique([asset_url,*safe_fallbacks])
            # ADR-003 stays true even for same-origin optimized derivatives:
            # video playback uses media_* only; preview/external are not UI paths.
            record["preview_url"]=""; record["preview_candidates"]=[]; record["external_url"]=""
            record["hosted_video"]=True; record["hosted_video_optimized"]=bool(optimized)
            record["playback_mode"]="same-origin-web"
            record["hero_autoplay"]=True; record["autoplay_grid"]=True
            record.pop("video_chunk_urls",None); record.pop("video_chunk_mime",None)
            record.pop("video_chunk_bytes",None); record.pop("hosted_video_chunked",None)

    ffmpeg: Path|None=None; ffprobe: Path|None=None; ffmpeg_meta: dict[str,Any]={}
    ffmpeg_attempted=False
    media_ids=list(by_id.keys())
    for position, media_id in enumerate(media_ids):
        records=by_id[media_id]
        remaining_count=max(1,len(media_ids)-position)
        remaining_budget=max(0,max_total_bytes-total)
        # Keep a real margin inside the video budget instead of consuming every
        # byte and discovering the problem only at publication preflight.
        minimum_allocation=min(3*1024*1024,max(512*1024,int(preferred_target_bytes)))
        allocation=min(preferred_target_bytes,max(minimum_allocation,int((remaining_budget/remaining_count)*0.92)))
        allocation=min(allocation,max(512*1024,direct_file_bytes-256*1024))
        if remaining_budget < 512*1024 or allocation < 512*1024:
            skipped.append({"id":media_id,"reason":"orçamento de vídeo web esgotado"}); continue

        mime=str(records[0].get("mime") or "video/mp4").split(";",1)[0].casefold()
        safe_id=re.sub(r"[^a-zA-Z0-9_-]+","-",media_id).strip("-") or "video"
        modified_time=str(records[0].get("modified_time") or "")
        previous=previous_items.get(media_id) or {}
        target=media_dir/f"{safe_id}.mp4"
        if progress_callback:
            try: progress_callback({"stage":"video-check","index":position+1,"total":len(media_ids),"id":media_id,"cached":False})
            except Exception: pass

        # First reuse a derivative from the immediately previous build.
        try:
            prev_rel=str(previous.get("path") or "").strip("/")
            prev_path=reuse_dir.joinpath(*prev_rel.split("/")) if reuse_dir and prev_rel else None
            same_source=bool(modified_time and previous.get("modified_time")==modified_time)
            previous_optimized=bool(previous.get("optimized"))
            same_profile=(not previous_optimized) or str(previous.get("optimization_profile") or "")==WEB_VIDEO_PROFILE
            if same_source and same_profile and prev_path and prev_path.is_file() and prev_path.stat().st_size<=allocation:
                shutil.copy2(prev_path,target); size=target.stat().st_size; total+=size; reused_bytes+=size
                url=f"assets/media/{target.name}"; bind(records,url,optimized=previous_optimized)
                item={"id":media_id,"path":url,"bytes":size,"mime":"video/mp4","modified_time":modified_time,"sha256":_sha256_file(target),"optimized":previous_optimized,"source_bytes":int(previous.get("source_bytes") or size),"reused":True,"reuse_source":"previous-build"}
                if previous_optimized: item["optimization_profile"]=WEB_VIDEO_PROFILE
                hosted.append(item)
                continue
        except Exception as exc: write_log("build",f"Reuso incremental de {media_id} ignorado: {exc}")

        response=None
        try:
            # V7.12.8: persistent derivative cache is checked BEFORE Drive and can be recompressed locally.
            # Unchanged videos therefore require zero original download and zero FFmpeg.
            cached=web_cache_path(media_id,modified_time,target_bytes=allocation)
            if cached.is_file() and 1024<cached.stat().st_size<=allocation:
                shutil.copy2(cached,target); size=target.stat().st_size
                if total+size>max_total_bytes: raise ValueError("cache excederia orçamento total de vídeos")
                total+=size; reused_bytes+=size
                url=f"assets/media/{target.name}"; bind(records,url,optimized=True)
                hosted.append({"id":media_id,"path":url,"bytes":size,"mime":"video/mp4","modified_time":modified_time,"sha256":_sha256_file(target),"optimized":True,"optimization_profile":WEB_VIDEO_PROFILE,"source_bytes":int(previous.get("source_bytes") or 0),"target_bytes":allocation,"cache_hit":True})
                if progress_callback:
                    try: progress_callback({"stage":"video-cache-hit","index":position+1,"total":len(media_ids),"id":media_id,"cached":True,"bytes":size})
                    except Exception: pass
                continue

            # V7.12.8: an older V7.12.6/7 derivative may already exist but be
            # larger than the new REST-safe allocation. Re-encode that local
            # derivative before touching Drive, preserving all expensive work
            # from earlier publication attempts.
            if cached.is_file() and cached.stat().st_size>allocation:
                if not ffmpeg_attempted:
                    ffmpeg,ffprobe,ffmpeg_meta=ensure_ffmpeg(auto_install=True); ffmpeg_attempted=True
                if ffmpeg:
                    if progress_callback:
                        try: progress_callback({"stage":"video-cache-shrink","index":position+1,"total":len(media_ids),"id":media_id,"cached":True,"source_bytes":cached.stat().st_size})
                        except Exception: pass
                    local_source=cached.with_suffix('.source-cache.mp4')
                    local_source.unlink(missing_ok=True)
                    shutil.copy2(cached,local_source)
                    try:
                        optimization=optimize_video(local_source,cached,target_bytes=allocation,ffmpeg=ffmpeg,ffprobe=ffprobe)
                    finally:
                        local_source.unlink(missing_ok=True)
                    if 1024<cached.stat().st_size<=direct_file_bytes:
                        shutil.copy2(cached,target); size=target.stat().st_size
                        if total+size>max_total_bytes: raise ValueError("cache recomprimido excederia orçamento total de vídeos")
                        total+=size; reused_bytes+=size; optimized_bytes+=size
                        url=f"assets/media/{target.name}"; bind(records,url,optimized=True)
                        hosted.append({"id":media_id,"path":url,"bytes":size,"mime":"video/mp4","modified_time":modified_time,"sha256":_sha256_file(target),"optimized":True,"optimization_profile":WEB_VIDEO_PROFILE,"source_bytes":int(previous.get("source_bytes") or 0),"target_bytes":allocation,"cache_hit":True,"cache_reencoded":True,"video_kbit":int(optimization.get("video_kbit") or 0)})
                        continue

            if progress_callback:
                try: progress_callback({"stage":"video-download","index":position+1,"total":len(media_ids),"id":media_id,"cached":False})
                except Exception: pass
            response=media_provider.download_response(media_id)
            declared=int(response.headers.get("Content-Length") or 0)
            if declared and declared>max_source_bytes:
                raise ValueError(f"original com {declared/1024/1024:.1f} MiB excede limite de processamento web de {max_source_bytes/1024/1024:.0f} MiB")

            # A genuinely small MP4 is already ideal for progressive same-origin
            # playback and does not benefit from a lossy transcode.
            copy_direct=bool(mime=="video/mp4" and declared and declared<=allocation)
            if copy_direct:
                partial=target.with_suffix(".mp4.part"); written=0
                with partial.open("wb") as stream:
                    while True:
                        chunk=response.read(1024*1024)
                        if not chunk: break
                        written+=len(chunk)
                        if written>allocation or total+written>max_total_bytes: raise ValueError("MP4 direto excedeu a alocação web")
                        stream.write(chunk)
                if written<1024: raise ValueError("Drive não retornou bytes suficientes")
                partial.replace(target); total+=written; downloaded_bytes+=written
                try:
                    cached.parent.mkdir(parents=True,exist_ok=True); shutil.copy2(target,cached)
                except Exception as exc: write_log("build",f"Cache persistente do MP4 direto {media_id} não foi gravado: {exc}")
                url=f"assets/media/{target.name}"; bind(records,url,optimized=False)
                hosted.append({"id":media_id,"path":url,"bytes":written,"mime":"video/mp4","modified_time":modified_time,"sha256":_sha256_file(target),"optimized":False,"source_bytes":declared or written})
                continue

            # Larger sources are streamed to a temporary file and then converted.
            temp_root=data_root()/"cache"/"video-source-temp"; temp_root.mkdir(parents=True,exist_ok=True)
            with tempfile.TemporaryDirectory(prefix="sf-video-",dir=str(temp_root)) as td:
                source=Path(td)/"source.bin"; written=0
                with source.open("wb") as stream:
                    while True:
                        chunk=response.read(1024*1024)
                        if not chunk: break
                        written+=len(chunk)
                        if written>max_source_bytes: raise ValueError("original excedeu o limite de processamento web")
                        stream.write(chunk)
                if written<1024: raise ValueError("Drive não retornou bytes suficientes")
                downloaded_bytes+=written
                if mime=="video/mp4" and written<=allocation:
                    shutil.copy2(source,target); size=target.stat().st_size; total+=size
                    try:
                        cached.parent.mkdir(parents=True,exist_ok=True); shutil.copy2(target,cached)
                    except Exception as exc: write_log("build",f"Cache persistente do MP4 direto {media_id} não foi gravado: {exc}")
                    url=f"assets/media/{target.name}"; bind(records,url,optimized=False)
                    hosted.append({"id":media_id,"path":url,"bytes":size,"mime":"video/mp4","modified_time":modified_time,"sha256":_sha256_file(target),"optimized":False,"source_bytes":written})
                    continue

                if not ffmpeg_attempted:
                    ffmpeg,ffprobe,ffmpeg_meta=ensure_ffmpeg(auto_install=True); ffmpeg_attempted=True
                if not ffmpeg:
                    raise ValueError(f"otimizador FFmpeg indisponível: {ffmpeg_meta.get('reason','não localizado')}")

                cached=web_cache_path(media_id,modified_time,target_bytes=allocation)
                if progress_callback:
                    try: progress_callback({"stage":"video-optimize","index":position+1,"total":len(media_ids),"id":media_id,"cached":False,"source_bytes":written})
                    except Exception: pass
                optimization=optimize_video(source,cached,target_bytes=allocation,ffmpeg=ffmpeg,ffprobe=ffprobe)
                if cached.stat().st_size>direct_file_bytes:
                    # Retry once with a stricter byte target. This is rare but
                    # keeps every published media blob below the GitHub guard.
                    stricter=max(3*1024*1024,int(allocation*0.78)); cached.unlink(missing_ok=True)
                    cached=web_cache_path(media_id,modified_time,target_bytes=stricter)
                    optimization=optimize_video(source,cached,target_bytes=stricter,ffmpeg=ffmpeg,ffprobe=ffprobe)
                if cached.stat().st_size>direct_file_bytes:
                    raise ValueError(f"derivado web ainda ficou grande ({cached.stat().st_size/1024/1024:.1f} MiB)")
                shutil.copy2(cached,target); optimized_bytes+=target.stat().st_size
                size=target.stat().st_size
                if total+size>max_total_bytes: raise ValueError("derivado excederia orçamento total de vídeos")
                total+=size
                url=f"assets/media/{target.name}"; bind(records,url,optimized=True)
                hosted.append({"id":media_id,"path":url,"bytes":size,"mime":"video/mp4","modified_time":modified_time,"sha256":_sha256_file(target),"optimized":True,"optimization_profile":WEB_VIDEO_PROFILE,"source_bytes":written,"target_bytes":allocation,"video_kbit":int(optimization.get("video_kbit") or 0),"duration":float(optimization.get("duration") or 0)})
        except Exception as exc:
            target.unlink(missing_ok=True)
            skipped.append({"id":media_id,"reason":str(exc)})
            write_log("build",f"Vídeo {media_id} permaneceu no fallback do Drive: {exc}")
        finally:
            if response is not None:
                try: response.close()
                except Exception: pass

    stats={
        "hosted":len(hosted),"optimized":sum(1 for item in hosted if item.get("optimized")),
        "copied":sum(1 for item in hosted if not item.get("optimized")),
        "reused":sum(1 for item in hosted if item.get("reused") or item.get("cache_hit")),
        "failed":len(skipped),"skipped":len(skipped),"bytes":total,"items":hosted,"fallbacks":skipped,
        "reused_bytes":reused_bytes,"downloaded_bytes":downloaded_bytes,"optimized_bytes":optimized_bytes,
        "budget_bytes":max_total_bytes,"preferred_target_bytes":preferred_target_bytes,
        "mode":"same-origin-primary-cache-first-v7551","optimization_profile":WEB_VIDEO_PROFILE,
        "ffmpeg":{k:v for k,v in ffmpeg_meta.items() if k in {"available","installed","version","reason"}},
    }
    manifest["video_assets"]=copy.deepcopy(stats)
    return copy.deepcopy(stats)

def _public_video_delivery_summary(site_dir: Path, manifest: dict[str, Any]) -> dict[str, Any]:
    """Resolve public video readiness after same-origin materialization.

    A visible video is ready when a generated ``assets/media/*.mp4`` exists, or
    when materialization failed but backend validation previously proved a direct
    Drive byte source (Range/native). Browser-deferred/inconclusive candidates are
    useful runtime fallbacks, but do not count as publish-safe on their own.
    """
    records: dict[str, list[dict[str, Any]]] = {}
    def walk(value: Any) -> None:
        if isinstance(value, dict):
            if str(value.get("type") or "") == "video" and str(value.get("id") or ""):
                records.setdefault(str(value.get("id")), []).append(value)
            for child in value.values():
                walk(child)
        elif isinstance(value, list):
            for child in value:
                walk(child)
    walk(manifest)
    hosted=fallback_proven=failed=0
    items=[]
    for media_id,copies in records.items():
        same_origin=next((str(row.get("media_url") or "") for row in copies if row.get("hosted_video") and str(row.get("media_url") or "").startswith("assets/media/")),"")
        asset_ok=False
        if same_origin:
            candidate=site_dir.joinpath(*same_origin.split("/"))
            asset_ok=candidate.is_file() and 1024 < candidate.stat().st_size <= 7*1024*1024
        modes={str(row.get("playback_mode") or "") for row in copies}
        fallback_candidates=[]
        for row in copies:
            fallback_candidates.extend([str(v) for v in (row.get("media_candidates") or []) if _public_video_deferred_candidate_allowed(str(v))])
        proven=bool(modes & {"drive-native-range","drive-native-direct"}) and bool(fallback_candidates)
        if asset_ok:
            hosted+=1; status="hosted"
        elif proven:
            fallback_proven+=1; status="validated-drive-fallback"
        else:
            failed+=1; status="failed"
        items.append({"id":media_id,"status":status,"asset":same_origin if asset_ok else "","playback_modes":sorted(modes),"fallback_candidates":len(_unique(fallback_candidates))})
    return {"total":len(records),"hosted":hosted,"validated_fallback":fallback_proven,"failed":failed,"items":items,"same_origin_primary":True,"drive_viewer_forbidden":True}


def _apply_seo_head(template: str, route_meta: dict[str, Any] | None, *, site_name: str = "Mensagem Studio") -> str:
    if not isinstance(route_meta, dict):
        return template
    parts = [route_meta_html(route_meta, site_name=site_name)]
    structured = jsonld_for_route(route_meta, site_name=site_name)
    if structured:
        parts.append(structured)
    seo_head = "\n".join(parts)
    output = re.sub(r"<title>.*?</title>", seo_head, template, count=1, flags=re.IGNORECASE | re.DOTALL)
    language = escape(str(route_meta.get("language") or "pt-BR"), quote=True)
    output = re.sub(r'<html\s+lang="[^"]*">', f'<html lang="{language}">', output, count=1, flags=re.IGNORECASE)
    return output


def _route_shell(template: str, full_path: str, route_meta: dict[str, Any] | None = None, *, site_name: str = "Mensagem Studio") -> str:
    """Create a small route document backed by shared CSS, JS and JSON."""
    normalized = str(full_path or "").strip("/")
    depth = max(1, len([part for part in normalized.split("/") if part]))
    prefix = "../" * depth
    fallback = f"{prefix}index.html?sf_route={quote(normalized, safe='')}"
    asset_version = quote(str(BUILD_ID or APP_VERSION), safe='')
    bootstrap = (
        f'<script data-studioframe-route-shell>window.__PB_ASSET_BASE__={json.dumps(prefix)};window.__PB_BUILD_ID__={json.dumps(BUILD_ID)};'
        f'if(location.protocol==="file:"){{location.replace({json.dumps(fallback)}+location.hash);}}</script>'
        f'<link rel="stylesheet" href="{prefix}assets/site.css?v={asset_version}">'
    )
    shell = _apply_seo_head(template, route_meta, site_name=site_name)
    shell = shell.replace("<style>__PB_SITE_CSS__</style>", bootstrap)
    shell = shell.replace("<script>window.__PB_PUBLIC_DATA__=__PB_MANIFEST_JSON__;</script>", "")
    shell = shell.replace("<script>__PB_SITE_JS__</script>", f'<script src="{prefix}assets/site.js?v={asset_version}"></script>')
    return shell

def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


